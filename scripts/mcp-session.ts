// Writes the /mcp page's example session (data/marketing/mcp-session.json): score_brief's answer for
// the session's input and Claude's reply built from it. Replay (the default) runs score_brief on the
// recorded Qloo responses only: no key, no network, and a miss throws. --record answers misses live
// (with QLOO_API_KEY, within score_brief's own cap), saves them as a new fixture, then replays strictly.
//
//   npm run mcp:session [-- --record]
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { MCP_SESSION_FILE } from "../lib/marketing/mcp-session-data";
import { SCORE_INPUT, sessionReply } from "../lib/marketing/mcp-session";
import { scoreBrief, scoreBriefInputSchema, scoreBriefText } from "../lib/mcp/score-brief";
import { SCORE_BRIEF_BUDGET, SCORE_BRIEF_CAP } from "../lib/qloo/budget";
import { createQlooClient, type QlooClient } from "../lib/qloo/client";
import { createRunContext } from "../lib/qloo/context";
import { FixtureCache, findFixture, loadFixtures } from "../lib/qloo/fixtures";
import { RecordingCache } from "../lib/qloo/recording";
import { loadLocalEnv } from "./env";

function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

const run = (client: QlooClient) =>
  scoreBrief(scoreBriefInputSchema.parse(SCORE_INPUT), { client, ctx: createRunContext({ runId: "mcp-session", cap: SCORE_BRIEF_CAP, rowCaps: SCORE_BRIEF_BUDGET }) });

async function recordLive(): Promise<void> {
  loadLocalEnv();
  const apiKey = process.env.QLOO_API_KEY?.trim();
  if (!apiKey) fail("QLOO_API_KEY missing. Add it to your local env file (never commit it), then rerun.");
  const cache = new RecordingCache(loadFixtures());
  await run(createQlooClient({ apiKey, cache }));
  let name = "mcp-session";
  for (let n = 2; findFixture(name); n++) name = `mcp-session-${n}`;
  const file = await cache.save(name, "Qloo calls score_brief made live for the /mcp page's example session.", { secret: apiKey });
  console.log(`${cache.size} new Qloo answers${file ? ` (${file})` : ""}.`);
}

async function main(): Promise<void> {
  if (process.argv.includes("--record")) await recordLive();
  const result = await run(createQlooClient({ cache: FixtureCache.fromDir("fixtures", { strict: true }) }));
  if (result.status !== "scored") fail(`score_brief answered "${result.status}": ${result.notes.join(" ")}`);
  const session = {
    source: "score_brief for the /mcp example session's input (lib/marketing/mcp-session.ts SCORE_INPUT), replayed from the recorded Qloo responses. Generated by npm run mcp:session.",
    scoreAnswer: scoreBriefText(result),
    claudeReply: sessionReply(result),
  };
  await mkdir(path.dirname(MCP_SESSION_FILE), { recursive: true });
  // Qloo names may hold U+2014; written as an escape so the em dash scan stays clean.
  await writeFile(MCP_SESSION_FILE, `${JSON.stringify(session, null, 2).replace(/\u2014/g, "\\u2014")}\n`);
  console.log(`Wrote ${MCP_SESSION_FILE} (${result.calls.cached} cached Qloo answers, ${result.calls.live} live).`);
}

main().catch((error: unknown) => fail(error instanceof Error ? (error.stack ?? error.message) : String(error)));
